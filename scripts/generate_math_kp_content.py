def update_kp_content(db_path, subject_id, kp_contents):
    """更新知识点内容到数据库"""
    
    conn = sqlite3.connect(db_path)
    cursor = conn.cursor()
    
    updated = 0
    for kp_id, content in kp_contents.items():
        cursor.execute('''
            UPDATE knowledge_points 
            SET content = ?, updated_at = CURRENT_TIMESTAMP
            WHERE kp_id = ?
        ''', (content, kp_id))
        if cursor.rowcount > 0:
            updated += 1
            print(f'  ✅ 更新: {kp_id}')
        else:
            print(f'  ⚠️  未找到: {kp_id}')
    
    conn.commit()
    conn.close()
    
    return updated


